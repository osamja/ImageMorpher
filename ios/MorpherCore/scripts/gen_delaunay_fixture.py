import numpy as np
from scipy.spatial import Delaunay

# Deterministic random point set in general position (no co-circular ambiguity),
# so scipy's Delaunay triangulation is unique and directly comparable to the
# pure-Swift Bowyer-Watson implementation.
rng = np.random.default_rng(20261114)
pts = rng.uniform(0.0, 500.0, size=(30, 2))

tri = Delaunay(pts)
simplices = tri.simplices
norm = sorted([sorted(int(i) for i in s) for s in simplices],
              key=lambda t: (t[0], t[1], t[2]))

def fmt(p):
    return f"Point({float(p[0])!r}, {float(p[1])!r})"

lines = []
lines.append("// Auto-generated by scripts/gen_delaunay_fixture.py — do not edit by hand.")
lines.append("// Parity fixture produced with scipy.spatial.Delaunay (Qhull).")
lines.append("@testable import MorpherCore")
lines.append("")
lines.append("enum ParityFixture {")
lines.append("    static let points: [Point] = [")
for p in pts:
    lines.append(f"        {fmt(p)},")
lines.append("    ]")
lines.append("")
lines.append("    static let expectedTriangles: [[Int]] = [")
for t in norm:
    lines.append(f"        {t},")
lines.append("    ]")
lines.append("}")
print("\n".join(lines))
